#![forbid(unsafe_code)]

//! Cryptographic provider boundary for Ferrum Community.
//!
//! Phase 1.1 selects AWS-LC through aws-lc-rs and provides a narrow AES-256-GCM
//! adapter. The key hierarchy, canonical AAD encoder, durable nonce budget and
//! automatic key rotation are intentionally implemented in later Phase 1
//! subphases. This adapter must not be presented as the complete barrier.

use std::fmt;

use aws_lc_rs::aead::{AES_256_GCM, Aad, NONCE_LEN, Nonce, RandomizedNonceKey};
use zeroize::Zeroizing;

/// Exact cryptographic provider selected by the owner-approved ADR-0013.
pub const CRYPTO_PROVIDER_VERSION: &str = "aws-lc-rs/1.19.0";

/// Errors returned by the Community cryptographic adapter.
///
/// Error messages deliberately omit key material, plaintext, AAD and ciphertext.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CryptoError {
    /// AWS-LC rejected the supplied key.
    InvalidKey,
    /// Encryption could not be completed.
    EncryptionFailed,
    /// Authentication failed; plaintext must not be used.
    AuthenticationFailed,
}

impl fmt::Display for CryptoError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Self::InvalidKey => "invalid AES-256-GCM key",
            Self::EncryptionFailed => "AES-256-GCM encryption failed",
            Self::AuthenticationFailed => "AES-256-GCM authentication failed",
        })
    }
}

impl std::error::Error for CryptoError {}

/// AES-256-GCM adapter backed exclusively by AWS-LC.
///
/// AWS-LC generates a fresh random 96-bit nonce for every seal operation.
/// The nonce is returned in SealedPayload and must be stored with the
/// ciphertext. A caller must supply the same authenticated additional data
/// (AAD) when opening the payload.
///
/// This Phase 1.1 adapter does not yet enforce Ferrum's per-key nonce-use
/// budget, rotation threshold or key hierarchy. Those controls are required
/// before this primitive is integrated as the complete storage barrier.
pub struct Aes256GcmProvider {
    key: RandomizedNonceKey,
}

impl fmt::Debug for Aes256GcmProvider {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("Aes256GcmProvider")
            .field("provider", &CRYPTO_PROVIDER_VERSION)
            .field("algorithm", &"AES-256-GCM")
            .finish()
    }
}

impl Aes256GcmProvider {
    /// Constructs the AES-256-GCM provider from exactly 32 bytes of key
    /// material. The caller remains responsible for the source key's lifecycle.
    pub fn new(key_bytes: &[u8; 32]) -> Result<Self, CryptoError> {
        let key = RandomizedNonceKey::new(&AES_256_GCM, key_bytes)
            .map_err(|_| CryptoError::InvalidKey)?;
        Ok(Self { key })
    }

    /// Encrypts plaintext and authenticates AAD.
    ///
    /// AWS-LC generates the 96-bit nonce. The returned payload includes the
    /// nonce separately and stores the 128-bit authentication tag appended to
    /// the ciphertext.
    pub fn seal(&self, aad: &[u8], plaintext: &[u8]) -> Result<SealedPayload, CryptoError> {
        let mut scratch = Zeroizing::new(plaintext.to_vec());
        let nonce = self
            .key
            .seal_in_place_append_tag(Aad::from(aad), &mut *scratch)
            .map_err(|_| CryptoError::EncryptionFailed)?;

        let mut nonce_bytes = [0_u8; NONCE_LEN];
        nonce_bytes.copy_from_slice(nonce.as_ref().as_slice());

        // Move only the ciphertext out. The guard zeroizes any remaining
        // scratch buffer automatically, including on early return or unwind.
        let ciphertext_and_tag = std::mem::take(&mut *scratch);
        Ok(SealedPayload {
            nonce: nonce_bytes,
            ciphertext_and_tag,
        })
    }

    /// Authenticates and decrypts a payload using its original nonce and AAD.
    ///
    /// No plaintext is returned unless AWS-LC verifies the authentication tag.
    pub fn open(&self, aad: &[u8], payload: &SealedPayload) -> Result<Vec<u8>, CryptoError> {
        let nonce = Nonce::assume_unique_for_key(payload.nonce);
        let mut scratch = Zeroizing::new(payload.ciphertext_and_tag.clone());
        match self.key.open_in_place(nonce, Aad::from(aad), &mut scratch) {
            Ok(plaintext) => Ok(plaintext.to_vec()),
            Err(_) => Err(CryptoError::AuthenticationFailed),
        }
    }
}

/// Ciphertext envelope produced by Aes256GcmProvider.
///
/// ciphertext_and_tag contains the encrypted bytes followed by the full
/// 128-bit AES-GCM authentication tag. The 96-bit nonce is stored separately.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SealedPayload {
    /// Random 96-bit nonce generated by AWS-LC.
    pub nonce: [u8; NONCE_LEN],
    /// Ciphertext with the 128-bit authentication tag appended.
    pub ciphertext_and_tag: Vec<u8>,
}

#[cfg(test)]
mod tests {
    use super::{Aes256GcmProvider, CRYPTO_PROVIDER_VERSION, CryptoError};

    #[test]
    fn provider_round_trips_with_random_96_bit_nonces() {
        let key = [0x42_u8; 32];
        let provider = Aes256GcmProvider::new(&key).expect("valid AES-256 key");
        let plaintext = b"phase 1.1 provider smoke test";
        let aad = b"ferrum/community/provider-test";

        let first = provider.seal(aad, plaintext).expect("seal succeeds");
        let second = provider.seal(aad, plaintext).expect("seal succeeds");

        assert_eq!(first.nonce.len(), 12);
        assert_ne!(first.nonce, second.nonce);
        assert_eq!(
            provider.open(aad, &first).expect("open succeeds"),
            plaintext
        );
    }

    #[test]
    fn authentication_failure_never_returns_plaintext() {
        let key = [0x24_u8; 32];
        let provider = Aes256GcmProvider::new(&key).expect("valid AES-256 key");
        let payload = provider
            .seal(b"canonical aad", b"secret test plaintext")
            .expect("seal succeeds");

        assert_eq!(
            provider.open(b"different aad", &payload),
            Err(CryptoError::AuthenticationFailed)
        );

        let mut tampered = payload;
        let last = tampered
            .ciphertext_and_tag
            .last_mut()
            .expect("tag is present");
        *last ^= 0x01;

        assert_eq!(
            provider.open(b"canonical aad", &tampered),
            Err(CryptoError::AuthenticationFailed)
        );
    }

    #[test]
    fn diagnostics_do_not_include_key_material() {
        let key = [0xA5_u8; 32];
        let provider = Aes256GcmProvider::new(&key).expect("valid AES-256 key");
        let debug = format!("{provider:?}");

        assert!(debug.contains(CRYPTO_PROVIDER_VERSION));
        assert!(!debug.contains("a5a5a5a5"));
    }
}
